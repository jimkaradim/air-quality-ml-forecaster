"""Produce an honest, reproducible evaluation summary from a completed real-data run."""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def render(artifact_dir: str = "artifacts", results_dir: str = "results") -> None:
    source = Path(artifact_dir)
    target = Path(results_dir)
    target.mkdir(parents=True, exist_ok=True)
    report = json.loads((source / "metrics.json").read_text(encoding="utf-8"))
    predictions = pd.read_csv(source / "test_predictions.csv")
    if predictions.empty or "test" not in report.get("splits", {}):
        raise ValueError("No real test evaluation is available")

    report["report_generated_utc"] = datetime.now(timezone.utc).isoformat()
    (target / "metrics.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    # Visualize a contiguous *window* of the unseen chronological test period.
    window = predictions.tail(168).reset_index(drop=True)
    fig, ax = plt.subplots(figsize=(12, 4.8))
    ax.plot(window.index, window["actual_pm25"], label="Observed PM2.5", linewidth=1.7)
    ax.plot(window.index, window["predicted_pm25"], label="ML forecast", alpha=0.9)
    ax.plot(window.index, window["baseline_pm25"], label="Persistence baseline", alpha=0.7)
    ax.set_title("Historical 1-hour-ahead PM2.5 forecasts | last 168 test observations")
    ax.set_xlabel("Chronological test-set observation (not calendar time)")
    ax.set_ylabel("PM2.5 (µg/m³)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(target / "test_forecast_window.png", dpi=140)
    plt.close(fig)

    metrics_table = ["| Approach | MAE (µg/m³) | RMSE (µg/m³) | R² |",
                     "|---|---:|---:|---:|"]
    model = report["splits"]["test"]["model"]
    baseline = report["splits"]["test"]["persistence_baseline"]
    for name, scores in [("HistGradientBoostingRegressor", model),
                         ("Persistence (PM2.5 at t)", baseline)]:
        metrics_table.append(
            f"| {name} | {scores['MAE']:.4f} | {scores['RMSE']:.4f} | {scores['R2']:.4f} |"
        )
    improvement = baseline["MAE"] - model["MAE"]
    verdict = ("lower" if improvement > 0 else "higher" if improvement < 0 else "equal")
    summary = (
        "# Measured results on the original UCI Beijing PM2.5 dataset\n\n"
        "This evaluation was generated by running the repository training code on real historical "
        "UCI Beijing PM2.5 hourly observations (2010–2014); it is **not** synthetic test output.\n\n"
        "## Held-out chronological test split\n\n"
        + "\n".join(metrics_table) + "\n\n"
        + f"Model test MAE was **{verdict}** than the persistence baseline by "
          f"**{abs(improvement):.4f} µg/m³**. "
        + "This is one historical hold-out evaluation, not a guarantee of future performance.\n\n"
        + f"Test observations: **{report['splits']['test']['observations']:,}**. "
        + f"Evaluation method: {report['method']}.\n\n"
        + "![Last 168 held-out forecasts](test_forecast_window.png)\n\n"
        + "See [metrics.json](metrics.json) for metrics on train, validation and test splits. "
          "The screenshot above shows an indexed 168-observation test window, not a live forecast.\n\n"
        + "Dataset attribution: Chen, S. (2015), Beijing PM2.5, UCI ML Repository, CC BY 4.0. "
          "https://doi.org/10.24432/C5JS49\n"
    )
    (target / "EVALUATION.md").write_text(summary, encoding="utf-8")
    print(summary)


if __name__ == "__main__":
    render()
